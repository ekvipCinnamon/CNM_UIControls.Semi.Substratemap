/*
 * representations.mjs - one corpus, three representations, one assertion.
 *
 * WHY IT IS SHAPED THIS WAY. `parseE142Json` is not a second parser: it presents
 * a JSON document as the element interface `parseE142Xml` already takes and hands
 * it over (D-023). Every facet, every identity constraint and the whole token
 * decode are literally the same code for both formats, so an equivalence test
 * can only ever catch ONE class of defect - a structural mapping error, a member
 * read from the wrong place.
 *
 * That is precisely why the JSON fixtures must be HAND-AUTHORED. Generating them
 * with `e142DocumentToJson` would make this suite a restatement of Task 8's round
 * trip: `parse(serialize(parse(xml))) === parse(xml)` is already asserted there,
 * and it would pass whether or not the mapping is right. Rule 10 says it plainly
 * - a card generated by running the code under test can detect change but never
 * incorrectness. Each JSON fixture carries a `$comment` saying it was transcribed
 * from the XML bytes rather than produced.
 *
 * WHAT IS COMPARED. The parsed `E142Document`s, deeply, plus the SET of warning
 * codes. Not the warning text: a JSON document has no line numbers and its
 * structural paths differ in the places where an XML document has an attribute
 * and a JSON one has a member. Codes are the contract Task 7's Done-when named;
 * text is prose.
 *
 * COVERAGE IS A REGISTRY, NOT A GUESS. `expectedRepresentations()` answers which
 * representations a fixture base name must have. A missing counterpart is red;
 * so is an unregistered one. See PENDING_JSON.
 */

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

import { stubParseDocument } from '../xml-stub.mjs';

// The engine modules end with a classic-namespace bridge that reads TcHmi.
// Declared before the dynamic imports below, exactly as every other suite does.
globalThis.TcHmi ??= { Controls: {} };

const ENGINE = new URL('../../', import.meta.url).href;
const E142Xml = await import(ENGINE + 'E142Xml.js');
const E142Json = await import(ENGINE + 'E142Json.js');

export const XML_DIR = fileURLToPath(new URL('../fixtures/xml/', import.meta.url));
export const JSON_DIR = fileURLToPath(new URL('../fixtures/json/', import.meta.url));

/**
 * XML fixtures that have no JSON counterpart YET, with the task that owes it.
 *
 * This list is the Tasks 10-14 backlog in executable form, and it only shrinks.
 * Its length is asserted, so it cannot quietly grow: a NEW XML fixture with no
 * counterpart and no entry here turns the suite red, which is the Done-when.
 *
 * Deliberately not "everything not yet done" as a wildcard - a wildcard exemption
 * is an exemption nobody removes.
 */
export const PENDING_JSON = new Map([
    /* Owed by a named task. Classified by what the fixture BODY exercises, with
     * XML comments stripped first - a fixture that only mentions a feature in its
     * header does not exercise it, and three did exactly that. */

    /* XML-only by nature: there is no JSON analogue of a truncated document. */
    ['v0211-invalid-truncated', 'XML-ONLY BY NATURE — a truncated document has no JSON analogue'],

    /* Belongs with the size table rather than a feature task. */

]);

/**
 * E142 JSON fixtures that the SCHEMA must reject and the PARSER must accept.
 *
 * Not an exemption list - the opposite. D-019 states the asymmetry deliberately:
 * the schema is the engineering-time contract and is strict, the parser reads
 * other producers' documents at runtime and may be looser, never stricter
 * (ground truth 5). A corpus with no schema-invalid document leaves that claim
 * untested, so these fixtures are the test of it, and the suite asserts they
 * fail validation rather than skipping them.
 *
 * Each entry names the member the schema rejects, so a fixture that starts
 * failing for a DIFFERENT reason is not silently absorbed.
 */
export const SCHEMA_INVALID = new Map([
    ['v0125-transfer-degenerate',
        { at: 'FromSubstrateId',
          why: 'a TransferMap omits one of the three From* the XSD declares use="required". '
            + 'The schema refuses it; the parser warns E142_XML_TRANSFER_FROM_MISSING, keeps the '
            + 'map and parses on, because the rest of the document is still a usable map.' }],
    ['v0125-devicedata-degenerate',
        { at: 'F8',
          why: 'the STANDARD\'S OWN R1-2.1 example writes an array of three doubles as a single '
            + 'ccs:F8, which is xsd:double. xmllint rejects the XML and this schema rejects the '
            + 'JSON; the parser reports E138_PV_LEXICAL, drops the value to null and continues, '
            + 'because a consumer meets this document in the field.' }],
    ['official-BinCodeMap-Extension-Example',
        { at: 'Substrates',
          why: 'SEMI\'s own extension example hangs a vendor subtree off Substrate. The schema is '
            + 'additionalProperties:false and refuses it; the parser warns E142_JSON_UNKNOWN_MEMBER, '
            + 'drops it and keeps every base-schema field. Rejecting a document over a producer\'s '
            + 'extension is the failure Rule 9 forbids - and extension is what the example is FOR.' }],
]);

/**
 * Fixtures whose two representations must produce EQUAL DOCUMENTS but different
 * warning CODES, with the pair of codes named.
 *
 * Two causes, both structural rather than defects, and both traceable to a
 * property XML has and JSON has not:
 *
 *  1. NAMESPACES. Extension content hung off a foreign namespace is
 *     `E142_XML_FOREIGN_NAMESPACE_SKIPPED`; the same content in JSON is an
 *     unrecognised member, `E142_JSON_UNKNOWN_MEMBER`. Same fate - counted,
 *     reported, dropped, because `E142Document` has no slot for extension content
 *     on either path (observation 19, DEV-004) - by a different mechanism.
 *
 *  2. LEXICAL DIALECT. Every XML value is text, so `TopLevel="True"` needs a
 *     tolerance and a warning; JSON has a real boolean and there is nothing to
 *     tolerate, so `json` is `null` - no counterpart code, deliberately. This is
 *     JSON-FORMAT.md section 4 in practice: the XML dialect tolerances are NOT
 *     reproduced, because there is no legacy JSON producer to be tolerant of.
 *
 * Named rather than exempted: the suite asserts the documents ARE equal and that
 * each path raises exactly what is recorded here - including the ABSENCE, which
 * is why a `null` is written rather than the entry simply being left out.
 */
export const WARNING_CODES_DIFFER = new Map([
    ['official-BinCodeMap-Extension-Example',
        { xml: 'E142_XML_FOREIGN_NAMESPACE_SKIPPED', json: 'E142_JSON_UNKNOWN_MEMBER',
          why: 'a vendor subtree: a foreign NAMESPACE in XML, an unknown MEMBER in JSON. '
            + 'Neither path retains it and neither refuses the document.' }],
    ['v1005-strip-integer2-lowerleft',
        { xml: 'E142_XML_BOOLEAN_DIALECT', json: null,
          why: 'the document writes TopLevel="True" with a capital T, which xs:boolean does not '
            + 'accept. XML needs a tolerance and reports using it; JSON carries a real boolean and '
            + 'has nothing to tolerate, so it raises NOTHING - not a missing warning, an absent '
            + 'problem.' }],
]);

/**
 * Every XML fixture base name in the corpus.
 * @returns The base names, sorted.
 */
export function xmlFixtures() {
    return readdirSync(XML_DIR)
        .filter((n) => n.endsWith('.xml'))
        .map((n) => n.slice(0, -4))
        .sort();
}

/**
 * Every E142 JSON fixture base name.
 *
 * Selected by the DISCRIMINATOR, not by directory: `fixtures/json/` also holds
 * twenty `GridData` documents, a different contract with a camelCase vocabulary
 * and no `$format` at all. Reading them as E142 would fail on every member.
 * @returns `{ e142, gridData }`, both sorted base-name arrays.
 */
export function jsonFixtures() {
    const e142 = [];
    const gridData = [];
    for (const name of readdirSync(JSON_DIR).filter((n) => n.endsWith('.json')).sort()) {
        const doc = JSON.parse(readFileSync(join(JSON_DIR, name), 'utf8'));
        (doc.$format === 'semi-e142' ? e142 : gridData).push(name.slice(0, -5));
    }
    return { e142, gridData };
}

/**
 * Which representations a fixture must have, and which it does have.
 * @param base A fixture base name.
 * @returns `{ base, xml, json, pending }`.
 */
export function expectedRepresentations(base) {
    return {
        base,
        xml: existsSync(join(XML_DIR, base + '.xml')),
        json: existsSync(join(JSON_DIR, base + '.json')),
        pending: PENDING_JSON.get(base) ?? null,
    };
}

/** Documents carry `Uint32Array` and `Map`; render both comparably. */
export const normalize = (doc) => JSON.stringify(doc, (k, v) =>
    (ArrayBuffer.isView(v) ? Array.from(v) : (v instanceof Map ? [...v] : v)));

/** The leading `CODE` of each warning, sorted - the contract, without the prose. */
export const warningCodes = (warnings) => warnings.map((w) => w.split(/[: ]/)[0]).sort();

/**
 * Parses every available representation of one fixture and compares them.
 *
 * A representation that THROWS is recorded rather than propagated: several
 * fixtures are deliberately invalid, and "both paths rejected it with the same
 * error code" is itself an equivalence worth asserting.
 * @param base The fixture base name.
 * @returns `{ base, xml, json, equal, sameWarnings, detail }`.
 */
export function compareRepresentations(base) {
    const read = (fn) => {
        try { return { ok: true, ...fn() }; } catch (e) { return { ok: false, code: e.code ?? e.name }; }
    };
    const xmlPath = join(XML_DIR, base + '.xml');
    const jsonPath = join(JSON_DIR, base + '.json');

    const xml = existsSync(xmlPath)
        ? read(() => E142Xml.parseE142Xml(readFileSync(xmlPath, 'utf8'), { parseDocument: stubParseDocument }))
        : null;
    const json = existsSync(jsonPath)
        ? read(() => E142Json.parseE142Json(readFileSync(jsonPath, 'utf8')))
        : null;

    if (xml === null || json === null) {
        return { base, xml, json, equal: null, sameWarnings: null, detail: 'only one representation' };
    }
    if (!xml.ok || !json.ok) {
        const same = xml.ok === json.ok && xml.code === json.code;
        return {
            base, xml, json, equal: same, sameWarnings: same,
            detail: same ? `both rejected with ${xml.code}`
                : `xml ${xml.ok ? 'parsed' : xml.code}, json ${json.ok ? 'parsed' : json.code}`,
        };
    }

    const a = normalize(xml.doc);
    const b = normalize(json.doc);
    let detail = '';
    if (a !== b) {
        let i = 0;
        while (i < Math.min(a.length, b.length) && a[i] === b[i]) { i++; }
        detail = `documents differ at offset ${i}\n        xml : ${a.slice(Math.max(0, i - 60), i + 60)}`
            + `\n        json: ${b.slice(Math.max(0, i - 60), i + 60)}`;
    }
    const wx = warningCodes(xml.warnings);
    const wj = warningCodes(json.warnings);
    if (JSON.stringify(wx) !== JSON.stringify(wj)) {
        detail += `${detail ? '; ' : ''}warning codes differ: xml ${JSON.stringify(wx)} json ${JSON.stringify(wj)}`;
    }
    return {
        base, xml, json,
        equal: a === b,
        sameWarnings: JSON.stringify(wx) === JSON.stringify(wj),
        detail,
    };
}
