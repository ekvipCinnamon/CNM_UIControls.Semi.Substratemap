#!/usr/bin/env node
/*
 * hit-oracle.mjs - capture a hit-test oracle from a real browser.
 *
 * WHY THIS EXISTS. `tests/lib/dom-shims.mjs` implements `isPointInPath` and
 * `isPointInStroke` for Node, and every assertion about an item hit rests on
 * them being right. They are checked against expectations read off the geometry
 * by hand, which is honest for a rectangle and a circle and gets soft near the
 * boundary of a flattened cubic. There is no browser in this workspace to check
 * them against - Playwright and Cypress cannot run here, because the browser
 * binaries come from hosts the egress proxy refuses.
 *
 * So the oracle is captured ONCE, by hand, on a machine that has a browser, and
 * checked in as a fixture. After that the comparison is a plain Node assertion
 * that runs in the gate list for ever.
 *
 * WHAT IT IS NOT. It does not load `Engine.js`, and that is deliberate. The
 * question is not "does the control work in Chrome" - the live view already
 * answers that - it is "does this shim's geometry agree with Chrome's". So the
 * page carries nothing but shapes, transforms and points, and calls Chrome's own
 * `Path2D` and `CanvasRenderingContext2D`. No module imports, so no local server
 * and no CORS: a `file://` page is enough.
 *
 * Rule 10 asks that expectations not be generated by running the code under
 * test. Chrome is not the code under test. It is the platform the control ships
 * on, and the shim exists to imitate it.
 *
 * HOW TO USE IT
 *
 *   1. node tools/hit-oracle.mjs            writes tools/hit-oracle.html
 *   2. open that file in Chrome             it runs on load and shows a table
 *   3. press "Download hit-oracle.json"
 *   4. move the file to
 *      Helpers/SubstrateMapEngine/tests/fixtures/hit-oracle.json
 *
 * Step 2 is the manual step, in the same class as the `pdftotext` pass over
 * `pdf/` and the tier-3 contact sheet: an input the workspace cannot produce for
 * itself. It is NOT a gate. `e142-representations` section 23 consumes the
 * fixture when it is there and says plainly when it is not, because a silently
 * skipped comparison is the failure this whole area of the tree is about.
 *
 * Run: node tools/hit-oracle.mjs [--print]
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const ROOT = join(fileURLToPath(new URL('../', import.meta.url)));

/*
 * SWEEP_UNIT, transcribed from Controls/SubstrateMap/SubstrateMap.ts as the `d`
 * string `serializeCommand` would emit for it at prefix 'milli' and scale 1. The
 * demo die, and the only curve geometry this package builds.
 */
const SWEEP_D = 'M 0.10883 -0.16667 L -0.01129 -0.0002 L -0.11528 0.1445'
    + ' C -0.11931 0.15216 -0.12092 0.16022 -0.12132 0.16667'
    + ' C -0.12173 0.17594 -0.12011 0.18279 -0.12011 0.18279'
    + ' C -0.11528 0.20496 -0.06247 0.23478 -0.06247 0.23478'
    + ' L 0.11326 0.33233 L 0.11326 0.33394 L 0.11326 0.5 L -0.08706 0.40206'
    + ' C -0.1181 0.38674 -0.13664 0.36014 -0.14752 0.33313'
    + ' C -0.16405 0.29283 -0.16405 0.25292 -0.16405 0.25292'
    + ' L -0.16364 0.16667 L -0.16324 0.02721'
    + ' C -0.16324 0.01753 -0.16284 0.00867 -0.16163 -0.0002'
    + ' C -0.15518 -0.05341 -0.12938 -0.0917 -0.12938 -0.0917'
    + ' L -0.07537 -0.16667 L 0.04434 -0.33353 L 0.16405 -0.5'
    + ' L 0.16405 -0.33353 L 0.16405 -0.24365 L 0.10883 -0.16667 Z';

/**
 * The shapes to probe. `build` is a list of `[method, ...args]` replayed against
 * a Path2D on both sides, so the page and the suite construct the same object
 * from the same instructions rather than from two descriptions of one.
 */
const SHAPES = [
    { id: 'rect-14x10', build: [['rect', -7, -5, 14, 10]] },
    { id: 'circle-r5', build: [['arc', 0, 0, 5, 0, 6.283185307179586]] },
    { id: 'ellipse-8x3', build: [['ellipse', 0, 0, 8, 3, 0, 0, 6.283185307179586]] },
    { id: 'ellipse-rotated', build: [['ellipse', 0, 0, 8, 3, 0.6435011087932844, 0, 6.283185307179586]] },
    {
        id: 'concave-L',
        build: [['moveTo', 0, 0], ['lineTo', 10, 0], ['lineTo', 10, 4], ['lineTo', 4, 4],
            ['lineTo', 4, 10], ['lineTo', 0, 10], ['closePath']],
    },
    { id: 'sweep-unit', d: SWEEP_D },
    { id: 'sweep-die', d: SWEEP_D, scale: 22, offset: [6, 13] },
];

/** Transforms to set before probing, as `setTransform` argument lists. */
const TRANSFORMS = [
    { id: 'identity', m: [1, 0, 0, 1, 0, 0] },
    { id: 'scale2-translate', m: [2, 0, 0, 2, 100, 60] },
    { id: 'yflip', m: [1.5, 0, 0, -1.5, 200, 200] },
    { id: 'rotate30-scale', m: [1.299038, 0.75, -0.75, 1.299038, 120, 90] },
];

/** Stroke widths probed with round caps and joins, matching `getItemAtPos`. */
const LINE_WIDTHS = [0, 1, 3];

/**
 * A lattice of probe points in USER space, dense enough that a boundary shifted
 * by a fraction of a unit shows up as a changed answer somewhere.
 * @param shape The shape entry.
 * @returns `[x, y]` pairs.
 */
function probesFor(shape) {
    const s = shape.scale ?? 1;
    const [ox, oy] = shape.offset ?? [0, 0];
    const span = shape.id.startsWith('sweep') ? 0.6 * s : 14;
    const out = [];
    for (let i = -6; i <= 6; i++) {
        for (let j = -6; j <= 6; j++) {
            out.push([ox + (i * span) / 6, oy + (j * span) / 6]);
        }
    }
    return out;
}

const PLAN = SHAPES.map((shape) => ({ ...shape, probes: probesFor(shape) }));

/**
 * Builds one plan shape into a `Path2D`.
 *
 * ONE implementation, used by both sides: the suite imports it, and the page gets
 * its SOURCE inlined below via `toString()`. Two copies of this would be two
 * descriptions of one shape, and the oracle would then be comparing the shim
 * against a shape the browser never drew.
 * @param shape  A plan entry.
 * @param P      The `Path2D` constructor to use.
 * @param Matrix The `DOMMatrix` constructor to use.
 * @returns The built path.
 */
export function buildShapePath(shape, P, Matrix) {
    if (shape.d !== undefined) {
        const p = new P(shape.d);
        if (shape.scale === undefined && shape.offset === undefined) { return p; }
        const s = shape.scale ?? 1;
        const o = shape.offset ?? [0, 0];
        const out = new P();
        out.addPath(p, new Matrix([s, 0, 0, s, o[0], o[1]]));
        return out;
    }
    const p = new P();
    for (const [method, ...args] of shape.build) { p[method](...args); }
    return p;
}

/** The capture plan, imported by `e142-representations` so both sides agree. */
export const ORACLE_PLAN = { shapes: PLAN, transforms: TRANSFORMS, lineWidths: LINE_WIDTHS };

const PAGE = `<!DOCTYPE html>
<meta charset="utf-8">
<title>SubstrateMap hit oracle</title>
<style>
  body { font: 13px/1.5 system-ui, sans-serif; margin: 2rem; max-width: 60rem; }
  code, pre { font-family: ui-monospace, monospace; }
  pre { background: #f4f4f4; padding: .75rem; overflow-x: auto; }
  button { font: inherit; padding: .5rem 1rem; }
  .ok { color: #225F79; } .warn { color: #b03a1a; }
</style>
<h1>SubstrateMap hit oracle</h1>
<p>This page asks <strong>this browser</strong> what its own <code>Path2D</code>,
<code>isPointInPath</code> and <code>isPointInStroke</code> answer for a fixed set of shapes,
transforms and points. Nothing from the control is loaded; the answers are the browser's.</p>
<p>Press the button, then move the downloaded file to
<code>Helpers/SubstrateMapEngine/tests/fixtures/hit-oracle.json</code> in the workspace.</p>
<p><button id="dl">Download hit-oracle.json</button> <span id="status"></span></p>
<pre id="summary">running…</pre>
<script>
const PLAN = ${JSON.stringify(PLAN)};
const TRANSFORMS = ${JSON.stringify(TRANSFORMS)};
const LINE_WIDTHS = ${JSON.stringify(LINE_WIDTHS)};

${buildShapePath.toString()}
const buildPath = (shape) => buildShapePath(shape, Path2D, DOMMatrix);

const canvas = document.createElement('canvas');
canvas.width = 400; canvas.height = 400;
const ctx = canvas.getContext('2d');
ctx.lineCap = 'round';
ctx.lineJoin = 'round';

const cases = [];
for (const shape of PLAN) {
  const path = buildPath(shape);
  for (const t of TRANSFORMS) {
    ctx.setTransform(...t.m);
    // The page probes in USER space and converts, so the suite can do the same
    // arithmetic with its own matrix and compare like with like.
    const m = new DOMMatrix(t.m);
    for (const [ux, uy] of shape.probes) {
      const pt = m.transformPoint(new DOMPoint(ux, uy));
      const row = { shape: shape.id, transform: t.id, user: [ux, uy],
                    canvas: [pt.x, pt.y], inPath: ctx.isPointInPath(path, pt.x, pt.y), inStroke: {} };
      for (const w of LINE_WIDTHS) {
        ctx.lineWidth = w;
        row.inStroke[w] = ctx.isPointInStroke(path, pt.x, pt.y);
      }
      cases.push(row);
    }
  }
}
ctx.setTransform(1, 0, 0, 1, 0, 0);

const payload = {
  capturedBy: navigator.userAgent,
  capturedAt: new Date().toISOString(),
  note: 'Generated by tools/hit-oracle.mjs and captured in a browser. Regenerate only if the '
      + 'shapes, transforms or probe lattice in that file change.',
  plan: { shapes: PLAN, transforms: TRANSFORMS, lineWidths: LINE_WIDTHS },
  cases,
};

const inside = cases.filter((c) => c.inPath).length;
document.getElementById('summary').textContent =
  cases.length + ' cases across ' + PLAN.length + ' shapes and ' + TRANSFORMS.length
  + ' transforms\\n' + inside + ' of them inside the fill\\n\\n'
  + PLAN.map((s) => '  ' + s.id.padEnd(16) + s.probes.length + ' probes').join('\\n');

document.getElementById('dl').addEventListener('click', () => {
  const blob = new Blob([JSON.stringify(payload, null, 1)], { type: 'application/json' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = 'hit-oracle.json';
  a.click();
  document.getElementById('status').textContent = 'written — move it to tests/fixtures/';
  document.getElementById('status').className = 'ok';
});
</script>
`;

/*
 * Side effects behind a main guard: `e142-representations` imports ORACLE_PLAN
 * and buildShapePath from this file, and an import that wrote a 38 KB HTML file
 * would dirty the tree on every `node --test` run.
 */
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main();
}

/** Writes the page and reports. @returns Nothing. */
function main() {
const out = join(ROOT, 'tools/hit-oracle.html');
writeFileSync(out, PAGE);
const probes = PLAN.reduce((n, s) => n + s.probes.length, 0);
console.log('\n  hit oracle');
console.log('='.repeat(29));
console.log(`  shapes          : ${PLAN.length}`);
console.log(`  transforms      : ${TRANSFORMS.length}`);
console.log(`  probes / shape  : ${PLAN.map((s) => s.probes.length).join(', ')}`);
console.log(`  cases to capture: ${probes * TRANSFORMS.length}`);
console.log('='.repeat(29));
console.log(`  wrote ${out}`);
console.log('  open it in a browser, press the button, and move hit-oracle.json to');
console.log('  Helpers/SubstrateMapEngine/tests/fixtures/\n');

if (process.argv.includes('--print')) {
    console.log(JSON.stringify(ORACLE_PLAN, null, 1));
}
}
